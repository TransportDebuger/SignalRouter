/**
 * @file SignalRouter.hpp
 * @brief Асинхронный маршрутизатор POSIX-сигналов с поддержкой RAII и
 * потокобезопасностью
 *
 * @author Artem Ulyanov
 * @date Апрель 2026
 * @version 1.0
 *
 * @details
 * Класс SignalRouter обеспечивает безопасную и асинхронную обработку сигналов
 * в многопоточной среде с использованием signalfd и epoll.
 *
 * Основные возможности:
 * - Регистрация нескольких обработчиков на один сигнал.
 * - Потокобезопасная модификация и вызов обработчиков.
 * - Асинхронная доставка сигналов через event loop (epoll).
 * - RAII-совместимость: автоматическая очистка ресурсов.
 * - Неблокирующая обработка с использованием SFD_NONBLOCK.
 *
 * @note
 * - Все методы, кроме конструктора, не выбрасывают исключений (но могут
 * завершаться аварийно при ошибках программной логики).
 * - Методы start() и stop() идемпотентны при корректном использовании.
 *
 * @warning
 * - Работает только на Linux (требует signalfd, epoll).
 * - Не поддерживает SIGKILL и SIGSTOP.
 * - Не используйте этот класс в окружении, где сигналы уже обрабатываются иными
 * способами.
 * - Не создавайте более одного экземпляра в одном процессе.
 */
#pragma once

#include <functional>
#include <memory>

namespace stc {

/**
 * @class SignalRouter
 * @brief Потокобезопасный асинхронный маршрутизатор POSIX-сигналов.
 *
 * Предоставляет централизованную и безопасную обработку сигналов в
 * Linux-приложениях с использованием signalfd и отдельного рабочего потока.
 * Позволяет регистрировать и вызывать несколько обработчиков для одного сигнала
 * в контексте обычного потока, что исключает использование async-signal-unsafe
 * функций в сигнальных обработчиках.
 *
 * @details
 * - Сигналы перехватываются через signalfd, преобразуя их в событие
 * ввода-вывода.
 * - Работа организована в отдельном потоке с циклом epoll_wait(), что
 * обеспечивает асинхронную и неблокирующую обработку.
 * - Поддержка множественных обработчиков на один сигнал — вызываются по
 * порядку.
 * - Класс следует RAII: при уничтожении восстанавливает исходную маску
 * сигналов.
 * - Все публичные методы являются потокобезопасными (защищены мьютексом).
 * - Обработчики вызываются без блокировки, что предотвращает взаимоблокировки.
 *
 * @note
 * - Доступ к функциональности — через экземпляр класса.
 * - Методы start() и stop() идемпотентны: повторный вызов start() игнорируется,
 *   повторный stop() безопасен.
 *
 * @warning
 * - Работает только на Linux (требует signalfd, epoll).
 * - Не может перехватывать SIGKILL и SIGSTOP — это запрещено ядром.
 * - Обработчики выполняются в рабочем потоке, поэтому долгие операции могут
 *   задерживать обработку других сигналов.
 * - Не используйте stop() внутри обработчика сигнала — это приведёт к дедлоку
 *   (поток будет ждать самого себя).
 *
 * @par Пример использования:
 * @code
 * stc::SignalRouter router;
 * router.registerHandler(SIGUSR1, [](int) {
 *     std::cout << "SIGUSR1 получен\n";
 * });
 * router.start();
 *
 * // ... приложение работает ...
 *
 * router.stop();
 * @endcode
 */
class SignalRouter {
public:
  /// @brief Тип функции-обработчика сигнала. Принимает номер сигнала.
  using Handler = std::function<void(int)>;

  SignalRouter();
  ~SignalRouter();

  SignalRouter(const SignalRouter &) = delete;
  SignalRouter &operator=(const SignalRouter &) = delete;
  SignalRouter(SignalRouter &&) = delete;
  SignalRouter &operator=(SignalRouter &&) = delete;

  void registerHandler(int signum, Handler handler);
  void unregisterHandler(int signum);

  void start();
  void stop() noexcept;

  bool isRunning() const noexcept;

private:
  class Impl;
  std::unique_ptr<Impl> impl_;
};

} // namespace stc
